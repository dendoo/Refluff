"""Build the 33.7 s human-performance edit without changing the cut 1 files.

Run from the project root:
    python Tools/steam_art/tiktok/scraper_upgrades/retake_human/build_cut.py

The 60 Hz replays preserve the recorded pointer timing at speed 1. Speech is
copied from the original MP3, with pauses moved to fit the longer performances.
This script writes only this retake's EDL and the new human_cut output folder.
"""
import copy
import hashlib
import json
import sys
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
sys.path.insert(0, str(ROOT / "Tools/steam_art/trailer"))
import make_trailer as M  # noqa: E402

BASE = HERE.parent
OUT = ROOT / "SteamStore/tiktok/scraper_upgrades/human_cut"
SOURCE = OUT.parent / "voice_source.mp3"
SR, FPS = 48000, 60
PRE, POST = 0.06, 0.14
# All durations and cuts are exact output-frame counts. The weak replay has
# 436 frames; only its last idle frame is omitted. The other takes are whole.
SHOTS = [
    ("scu_arrival", 300),
    ("scu_weak_human", 435),
    ("scu_shop_human", 360),
    ("scu_power_human", 501),
    ("scu_reveal_human", 426),
]
DURATION = sum(n for _, n in SHOTS) / FPS
# (source first/last audible edge, destination first audible edge, transcript)
PIECES = [
    (0.07, 2.84, 0.35, "Oh, come on. Is there even a carpet under all that?"),
    (3.49, 5.50, 5.50, "At this rate, I'll be scraping all week."),
    (6.68, 7.35, 12.45, "Wait..."),
    (7.81, 9.24, 13.55, "I can upgrade my scraper."),
    (10.20, 11.23, 15.75, "Max power."),
    (11.82, 12.89, 17.17, "Max size."),
    (13.69, 16.31, 26.70, "Okay... that might be overkill."),
    (17.00, 17.73, 29.90, "Refluff."),
    (17.99, 19.28, 30.90, "Wishlist it on Steam."),
]


def srt_time(t):
    ms = round(t * 1000)
    return "%02d:%02d:%02d,%03d" % (
        ms // 3600000, ms // 60000 % 60, ms // 1000 % 60, ms % 1000)


def human_recording(kind):
    path = ROOT / "SteamStore/_work/tiktok_scraper/human" / (kind + ".json")
    d = json.loads(path.read_text(encoding="utf-8"))
    if d.get("fixture") or d["kind"] != kind or not d["samples"]:
        raise ValueError("not a successful human performance: " + str(path))
    return {
        "file": path.relative_to(ROOT).as_posix(),
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "duration": d["duration"],
        "samples": len(d["samples"]),
        "end_reason": d["endReason"],
        "playback_speed": 1.0,
    }


def main():
    edl = copy.deepcopy(json.loads((BASE / "edl.json").read_text(encoding="utf-8")))
    if len(edl["shots"]) != len(SHOTS) or edl["fps"] != FPS:
        raise ValueError("base edit no longer has the expected five 60 fps shots")
    edl["status"] = (
        "Scraper upgrades TikTok cut2, 2026-10-17: actual human weak and strong "
        "performances replayed at speed 1; supplied VO preserved without retiming; "
        "33.7 s, centred captions. Generated by retake_human/build_cut.py.")
    edl["cover"]["t"] = 27.9
    edl["voice"]["wav"] = (OUT / "vo_aligned.wav").relative_to(ROOT).as_posix()
    frame = 0
    shot_report = []
    for s, (take, n) in zip(edl["shots"], SHOTS):
        s.update(start=frame / FPS, dur=n / FPS, take=take, speed=1.0)
        for t in s.get("titles", []):
            t["pos"]["x"] = 0.5
        shot_report.append({"take": take, "start": frame / FPS, "dur": n / FPS,
                            "first_frame": frame, "frames": n, "speed": 1.0})
        frame += n
    weak, strong = edl["shots"][1], edl["shots"][3]
    weak["note"] = (
        "Actual 7.003366 s human performance, 680 pointer samples; 60 Hz replay "
        "at speed 1, final idle frame trimmed. Same scene continues into shop.")
    strong["note"] = (
        "Actual 8.0316769 s human performance, 755 pointer samples, continuous "
        "60 Hz replay at speed 1. Full crust removal verified before reveal.")
    edl["shots"][2]["note"] = (
        "Real shop after the human weak pass. Final power purchase local3.5, "
        "final area purchase4.92, aligned to unretimed voice phrases.")
    edl["shots"][4]["note"] = (
        "Continuous state after human strong pass. Dirty pile remains; crust0. "
        "Reaction, logo and CTA align to unretimed supplied voice.")
    weak["titles"][0]["dur"] = 7.05
    weak["titles"][1]["pos"]["y"] = 0.65
    weak["titles"][2]["pos"]["y"] = 0.712
    strong["titles"][0]["dur"] = 8.2
    recordings = {kind: human_recording(kind) for kind in ("weak", "strong")}

    x = M.decode_audio(str(SOURCE), SR, cache=False)
    y = np.zeros((round(DURATION * SR), 2), np.float32)
    timing, last_written = [], 0
    for a, b, d, transcript in PIECES:
        i0 = round(max(0, a - PRE) * SR)
        i1 = min(len(x), round((b + POST) * SR))
        o = round((d - (a - i0 / SR)) * SR)
        if o < last_written or o < 0 or o + i1 - i0 > len(y):
            raise ValueError("piece overlap or out of range: " + transcript)
        seg = x[i0:i1] * M.ramp(i1 - i0, round(0.008 * SR),
                                round(0.025 * SR))[:, None]
        y[o:o + len(seg)] += seg
        last_written = o + len(seg)
        timing.append({"text": transcript, "source": [a, b], "start": d,
                       "end": round(d + b - a, 3),
                       "padded_destination": [round(o / SR, 3),
                                              round(last_written / SR, 3)]})
    OUT.mkdir(parents=True, exist_ok=True)
    wav = OUT / "vo_aligned.wav"
    with wave.open(str(wav), "wb") as f:
        f.setnchannels(2)
        f.setsampwidth(2)
        f.setframerate(SR)
        f.writeframes((np.clip(y, -1, 1) * 32767).astype("<i2").tobytes())
    (HERE / "edl.json").write_text(json.dumps(edl, indent=1) + "\n", encoding="utf-8")
    report = {
        "source": SOURCE.relative_to(ROOT).as_posix(),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "source_seconds": len(x) / SR, "duration": DURATION,
        "frames": frame, "fps": FPS, "sample_rate": SR,
        "speech_retime": 1.0, "human_replay_speed": 1.0,
        "scrape_without_speech": [18.24, 26.70],
        "scrape_absolute_silence": [18.38, 26.64],
        "human_recordings": recordings, "shots": shot_report, "phrases": timing,
    }
    (OUT / "timing.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    srt = []
    for i, p in enumerate(timing, 1):
        srt.extend([str(i), srt_time(p["start"]) + " --> " + srt_time(p["end"]),
                    p["text"], ""])
    (OUT / "subtitles.srt").write_text("\n".join(srt), encoding="utf-8")
    (OUT / "voiceover_en.txt").write_text("\n\n".join(p[3] for p in PIECES) + "\n", encoding="utf-8")
    print(json.dumps({"edl": (HERE / "edl.json").relative_to(ROOT).as_posix(),
                      "wav": wav.relative_to(ROOT).as_posix(), "seconds": len(y) / SR,
                      "frames": frame, "last_word": timing[-1]["end"],
                      "peak_dbfs": float(20 * np.log10(np.max(np.abs(y)) + 1e-9))}))


if __name__ == "__main__":
    main()
